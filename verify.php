                        empty($generalError) &&
                        isset($stmt) &&
                        $stmt instanceof mysqli_stmt
                    ) {

                        if ($stmt->execute()) {

                            $stmt->close();

                            // Delete temporary doctor verification photo
                            if (
                                $userType === 'doctor' &&
                                !empty($tempPhotoPath) &&
                                is_file($tempPhotoPath)
                            ) {
                                @unlink($tempPhotoPath);
                            }

                            unset($_SESSION['pending_verification']);

                            $_SESSION['csrf_token'] =
                                bin2hex(random_bytes(32));


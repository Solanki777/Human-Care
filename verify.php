                        empty($pending['email_otp_hash']) ||
                        empty($pending['email_otp_expires_at'])
                    ) {

                        $generalError =
                            "Email OTP is not available. Please resend the OTP.";

                    } elseif (
                        $pending['email_otp_expires_at'] < time()
                    ) {

                        $generalError =
                            "Email OTP has expired. Please resend the OTP.";

                    } elseif (
                        !password_verify(
                            $emailOtp,
                            $pending['email_otp_hash']
                        )
                    ) {

                        $generalError =
                            "Incorrect email OTP.";


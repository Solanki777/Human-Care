                                        $pending['license_number'],
                                        $pending['specialization'],
                                        $null,
                                        $photoType
                                    );

                                    $stmt->send_long_data(
                                        10,
                                        $photoData
                                    );
                                }
                            }
                        }
                    }
                   

                    /*
                    |--------------------------------------------------------------------------
                    | INSERT USER
                    |--------------------------------------------------------------------------
                    */

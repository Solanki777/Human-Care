                    $success =
                        "Your email is already verified.";

                } else {

                    $emailOtp =
                        trim($_POST['email_otp'] ?? "");

                    if (!preg_match('/^\d{6}$/', $emailOtp)) {

                        $generalError =
                            "Please enter a valid 6-digit email OTP.";

